// Regenerates src/scan/complianceSchema.generated.ts from Microsoft Graph's public metadata:
//
//   curl -o metadata.xml 'https://graph.microsoft.com/beta/$metadata'
//   node scripts/generate-compliance-schema.mjs metadata.xml
//
// A compliance policy is a typed Graph resource with a fixed set of properties per platform — there
// is no setting-definition endpoint to ask, the way there is for the Settings Catalog. The metadata
// document is the one place Graph states what those properties are and what each may hold, so that
// is what this reads: every entity type derived from deviceCompliancePolicy, each property's type,
// the members of the enums they use, and the fields of the objects some properties hold (restricted
// apps, OS build ranges, a custom script, WSL distributions) — plus the one thing that hangs off a
// policy rather than sitting on it: the actions for noncompliance.
import { readFileSync, writeFileSync } from "node:fs";

const xml = readFileSync(process.argv[2], "utf8");
const attr = (tag, name) => new RegExp(`\\b${name}="([^"]*)"`).exec(tag)?.[1];

const enums = {};
for (const [, head, body] of xml.matchAll(/<EnumType ([^>]*)>([\s\S]*?)<\/EnumType>/g)) {
  enums[attr(head, "Name")] = [...body.matchAll(/<Member ([^>]*)\/>/g)].map(([, m]) => attr(m, "Name"));
}

const scalar = (type) => ({ "Edm.Boolean": "boolean", "Edm.Int32": "integer", "Edm.String": "string" })[type];
const fieldsOf = (body) => {
  const fields = {};
  for (const [, p] of body.matchAll(/<Property ([^>]*?)\/?>/g)) {
    const type = attr(p, "Type");
    const enumName = type.replace(/^graph\./, "");
    if (scalar(type)) fields[attr(p, "Name")] = scalar(type);
    else if (enums[enumName]) {
      fields[attr(p, "Name")] = { enum: enumName };
      usedEnums[enumName] = enums[enumName];
    }
    // Anything else on an object (binary content, nested lists) isn't a value to show or compare.
  }
  return fields;
};
const complexBodies = {};
for (const [, head, body] of xml.matchAll(/<ComplexType ([^>]*)(?<!\/)>([\s\S]*?)<\/ComplexType>/g)) complexBodies[attr(head, "Name")] = body;

const types = {};
const usedEnums = {};
const usedObjects = {};
for (const [, head, body] of xml.matchAll(/<EntityType ([^>]*BaseType="graph\.deviceCompliancePolicy"[^>]*)(?<!\/)>([\s\S]*?)<\/EntityType>/g)) {
  const properties = {};
  for (const [, p] of body.matchAll(/<Property ([^>]*?)\/?>/g)) {
    const type = attr(p, "Type");
    const enumName = type.replace(/^graph\./, "");
    if (type === "Edm.Boolean") properties[attr(p, "Name")] = "boolean";
    else if (type === "Edm.Int32") properties[attr(p, "Name")] = "integer";
    else if (type === "Edm.String") properties[attr(p, "Name")] = "string";
    else if (enums[enumName]) {
      properties[attr(p, "Name")] = { enum: enumName };
      usedEnums[enumName] = enums[enumName];
    } else {
      const list = /^Collection\(graph\.(\w+)\)$/.exec(type);
      const objectName = list?.[1] ?? enumName;
      if (complexBodies[objectName] === undefined) continue;
      properties[attr(p, "Name")] = { object: objectName, list: Boolean(list) };
      usedObjects[objectName] = fieldsOf(complexBodies[objectName]);
    }
  }
  if (Object.keys(properties).length) types[attr(head, "Name")] = properties;
}

// One action for noncompliance (deviceComplianceScheduledActionForRule -> scheduledActionConfigurations).
const actionItem = /<EntityType Name="deviceComplianceActionItem"[^>]*>([\s\S]*?)<\/EntityType>/.exec(xml)[1];
usedObjects.deviceComplianceActionItem = fieldsOf(actionItem);

const sorted = (object) => Object.fromEntries(Object.entries(object).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(
  new URL("../src/scan/complianceSchema.generated.ts", import.meta.url),
  `// Generated by scripts/generate-compliance-schema.mjs from Graph's beta $metadata — do not edit by hand.

export type ComplianceFieldType = "boolean" | "integer" | "string" | { enum: string };
export type CompliancePropertyType = ComplianceFieldType | { object: string; list: boolean };

/** Every compliance policy type Graph defines, and what each of its properties holds. */
export const COMPLIANCE_TYPES: Record<string, Record<string, CompliancePropertyType>> = ${JSON.stringify(sorted(types), null, 2)};

/** Members of the enums those properties use, in Graph's order — the first is what an unset property reports. */
export const COMPLIANCE_ENUMS: Record<string, string[]> = ${JSON.stringify(sorted(usedEnums), null, 2)};

/** Fields of the objects some properties hold (one, or a list of them), and of one action for noncompliance. */
export const COMPLIANCE_OBJECTS: Record<string, Record<string, ComplianceFieldType>> = ${JSON.stringify(sorted(usedObjects), null, 2)};
`,
);
console.log(`${Object.keys(types).length} policy types, ${Object.values(types).reduce((n, t) => n + Object.keys(t).length, 0)} properties, ${Object.keys(usedEnums).length} enums, ${Object.keys(usedObjects).length} object types`);
