// Regenerates src/scan/complianceSchema.generated.ts from Microsoft Graph's public metadata:
//
//   curl -o metadata.xml 'https://graph.microsoft.com/beta/$metadata'
//   node scripts/generate-compliance-schema.mjs metadata.xml
//
// A compliance policy is a typed Graph resource with a fixed set of properties per platform — there
// is no setting-definition endpoint to ask, the way there is for the Settings Catalog. The metadata
// document is the one place Graph states what those properties are and what each may hold, so that
// is what this reads: every entity type derived from deviceCompliancePolicy, each property's type,
// and the members of the enums they use. Properties holding nested objects (restricted app lists,
// OS build ranges, custom scripts, WSL distributions) are left out: they aren't single values.
import { readFileSync, writeFileSync } from "node:fs";

const xml = readFileSync(process.argv[2], "utf8");
const attr = (tag, name) => new RegExp(`\\b${name}="([^"]*)"`).exec(tag)?.[1];

const enums = {};
for (const [, head, body] of xml.matchAll(/<EnumType ([^>]*)>([\s\S]*?)<\/EnumType>/g)) {
  enums[attr(head, "Name")] = [...body.matchAll(/<Member ([^>]*)\/>/g)].map(([, m]) => attr(m, "Name"));
}

const types = {};
const usedEnums = {};
for (const [, head, body] of xml.matchAll(/<EntityType ([^>]*BaseType="graph\.deviceCompliancePolicy"[^>]*)(?<!\/)>([\s\S]*?)<\/EntityType>/g)) {
  const properties = {};
  for (const [, p] of body.matchAll(/<Property ([^>]*?)\/?>/g)) {
    const type = attr(p, "Type");
    const enumName = type.replace(/^graph\./, "");
    if (type === "Edm.Boolean") properties[attr(p, "Name")] = "boolean";
    else if (type === "Edm.Int32") properties[attr(p, "Name")] = "integer";
    else if (type === "Edm.String") properties[attr(p, "Name")] = "string";
    else if (enums[enumName]) {
      properties[attr(p, "Name")] = { enum: enumName };
      usedEnums[enumName] = enums[enumName];
    }
  }
  if (Object.keys(properties).length) types[attr(head, "Name")] = properties;
}

const sorted = (object) => Object.fromEntries(Object.entries(object).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(
  new URL("../src/scan/complianceSchema.generated.ts", import.meta.url),
  `// Generated by scripts/generate-compliance-schema.mjs from Graph's beta $metadata — do not edit by hand.

export type CompliancePropertyType = "boolean" | "integer" | "string" | { enum: string };

/** Every compliance policy type Graph defines, and what each of its single-valued properties holds. */
export const COMPLIANCE_TYPES: Record<string, Record<string, CompliancePropertyType>> = ${JSON.stringify(sorted(types), null, 2)};

/** Members of the enums those properties use, in Graph's order — the first is what an unset property reports. */
export const COMPLIANCE_ENUMS: Record<string, string[]> = ${JSON.stringify(sorted(usedEnums), null, 2)};
`,
);
console.log(`${Object.keys(types).length} policy types, ${Object.values(types).reduce((n, t) => n + Object.keys(t).length, 0)} properties, ${Object.keys(usedEnums).length} enums`);
